"""Bundle every add-on .gs file into ONE file, for the simplest copy-paste install.

Apps Script loads all files of a project into one global scope, so one big file behaves exactly
like the separate files. Pasting one file (plus the manifest) avoids the most common setup
mistakes: a missing file, an old file left behind, or a half-pasted file that breaks the project.

    python scripts/bundle_addon.py      ->  addon_bundle/MailGuard.gs + addon_bundle/appsscript.json
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "addon"
OUT = ROOT / "addon_bundle"


def main() -> None:
    OUT.mkdir(exist_ok=True)
    files = sorted(SRC.glob("*.gs"))
    parts = [
        (
            "/**\n * MailGuard add-on - ALL files in one\n"
            " * (generated by scripts/bundle_addon.py; edit addon/*.gs instead).\n"
            " * Paste this whole file into a single script file in the Apps Script editor.\n */\n"
        )
    ]
    for f in files:
        parts.append(f"\n// ===================================================================== {f.name}\n\n")
        parts.append(f.read_text(encoding="utf-8"))
    (OUT / "MailGuard.gs").write_text("".join(parts), encoding="utf-8")
    shutil.copy(SRC / "appsscript.json", OUT / "appsscript.json")
    print(f"bundled {len(files)} files -> {OUT / 'MailGuard.gs'}")


if __name__ == "__main__":
    main()
